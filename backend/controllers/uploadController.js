const fs = require("fs");
const path = require("path");

const IMAGE_DIR = path.join(__dirname, "..", "uploads", "images");
const FILE_DIR = path.join(__dirname, "..", "uploads", "files");

const imageExtensions = [".jpg", ".jpeg", ".png", ".gif", ".tiff"];

const documentExtensions = [
  ".pdf",
  ".doc",
  ".docx",
  ".xls",
  ".xlsx",
  ".ppt",
  ".pptx",
  ".txt",
];

// Get uploaded items
const getItems = async (directory, allowedExtensions, req, res, next) => {
  try {
    const filenames = await fs.promises.readdir(directory);

    const items = await Promise.all(
      filenames
        .filter((name) =>
          allowedExtensions.includes(path.extname(name).toLowerCase()),
        )
        .map(async (filename) => {
          const filePath = path.join(directory, filename);
          const stats = await fs.promises.stat(filePath);

          if (!stats.isFile()) return null;

          return {
            filename,
            size: stats.size,
            uploadedAt: stats.birthtime,
          };
        }),
    );

    res.status(200).json({
      success: true,
      count: items.filter(Boolean).length,
      data: items.filter(Boolean),
    });
  } catch (error) {
    next(error);
  }
};

// Get image list
const getImages = (req, res, next) => {
  return getItems(IMAGE_DIR, imageExtensions, req, res, next);
};

// Get document list
const getFiles = (req, res, next) => {
  return getItems(FILE_DIR, documentExtensions, req, res, next);
};

// Validate generated filename
const getSafePath = (filename, directory, allowedExtensions) => {
  const extension = path.extname(filename).toLowerCase();

  // Only accept UUID-based filenames generated by the server
  const validName =
    /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.[a-z0-9]+$/i;

  if (!validName.test(filename) || !allowedExtensions.includes(extension)) {
    return null;
  }

  return path.join(directory, filename);
};

// Preview image
const previewImage = async (req, res, next) => {
  try {
    const filePath = getSafePath(
      req.params.filename,
      IMAGE_DIR,
      imageExtensions,
    );

    if (!filePath) {
      return res.status(400).json({
        success: false,
        message: "Invalid filename.",
      });
    }

    await fs.promises.access(filePath, fs.constants.R_OK);

    res.setHeader("X-Content-Type-Options", "nosniff");
    res.setHeader("Content-Disposition", "inline");

    res.sendFile(filePath);
  } catch (error) {
    if (error.code === "ENOENT") {
      return res.status(404).json({
        success: false,
        message: "Image not found.",
      });
    }

    next(error);
  }
};

// Download image or document
const downloadItem = (directory, extensions) => {
  return async (req, res, next) => {
    try {
      const filePath = getSafePath(req.params.filename, directory, extensions);

      if (!filePath) {
        return res.status(400).json({
          success: false,
          message: "Invalid filename.",
        });
      }

      await fs.promises.access(filePath, fs.constants.R_OK);

      res.download(filePath, req.params.filename, (error) => {
        if (error && !res.headersSent) {
          next(error);
        }
      });
    } catch (error) {
      if (error.code === "ENOENT") {
        return res.status(404).json({
          success: false,
          message: "File not found.",
        });
      }

      next(error);
    }
  };
};

// Delete image or document
const deleteItem = (directory, extensions) => {
  return async (req, res, next) => {
    try {
      const filePath = getSafePath(req.params.filename, directory, extensions);

      if (!filePath) {
        return res.status(400).json({
          success: false,
          message: "Invalid filename.",
        });
      }

      await fs.promises.unlink(filePath);

      res.status(200).json({
        success: true,
        message: "File deleted successfully.",
      });
    } catch (error) {
      if (error.code === "ENOENT") {
        return res.status(404).json({
          success: false,
          message: "File not found.",
        });
      }

      next(error);
    }
  };
};

// Upload success responses
const uploadImage = (req, res) => {
  res.status(201).json({
    success: true,
    message: "Image uploaded successfully.",
    data: {
      filename: req.file.filename,
      size: req.file.size,
    },
  });
};

const uploadFile = (req, res) => {
  res.status(201).json({
    success: true,
    message: "File uploaded successfully.",
    data: {
      filename: req.file.filename,
      size: req.file.size,
    },
  });
};

module.exports = {
  getImages,
  getFiles,
  previewImage,
  downloadImage: downloadItem(IMAGE_DIR, imageExtensions),
  downloadFile: downloadItem(FILE_DIR, documentExtensions),
  deleteImage: deleteItem(IMAGE_DIR, imageExtensions),
  deleteFile: deleteItem(FILE_DIR, documentExtensions),
  uploadImage,
  uploadFile,
};
